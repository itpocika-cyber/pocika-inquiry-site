export function getInquiries() {
  // Combine hardcoded mock data with any locally submitted data during the session
  const data = [...mockInquiries];
  
  try {
    const sessionDraft = sessionStorage.getItem('pocika_submitted_inquiry');
    if (sessionDraft) {
      const parsed = JSON.parse(sessionDraft);
      // Avoid duplicate if it's already in the list (simple check by ID)
      if (!data.find(i => i.inquiryNumber === parsed.inquiryNumber)) {
        data.push(parsed);
      }
    }
  } catch(e) {}
  
  // Sort newest first by default
  return data.sort((a, b) => new Date(b.submissionMeta.confirmedAt) - new Date(a.submissionMeta.confirmedAt));
}
